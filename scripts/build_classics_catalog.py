#!/usr/bin/env python3
"""Build the Research Hub's classics catalogue from open CTS/TEI corpora.

Reads the __cts__.xml catalogue files of local (sparse) clones of:
  PerseusDL/canonical-greekLit, PerseusDL/canonical-latinLit, OpenGreekAndLatin/First1KGreek
and writes tools/research/data/classics-catalog.js — a compact list of every work with its
available original-language editions and English translations, plus the raw GitHub URL
of each file so the browser can load any text on demand.

Get the catalogue files without downloading the texts (a few MB each):
  git clone --depth 1 --filter=blob:none --no-checkout https://github.com/PerseusDL/canonical-greekLit
  cd canonical-greekLit && git sparse-checkout set --no-cone '__cts__.xml' && git checkout

Usage:
  python3 scripts/build_classics_catalog.py CLONE_DIR [CLONE_DIR ...] [--out PATH]
"""
import argparse, json, os, subprocess, sys
import xml.etree.ElementTree as ET

TI = '{http://chs.harvard.edu/xmlns/cts}'
XL = '{http://www.w3.org/XML/1998/namespace}lang'
REPOS = {'canonical-greekLit': 'PerseusDL/canonical-greekLit',
         'canonical-latinLit': 'PerseusDL/canonical-latinLit',
         'First1KGreek': 'OpenGreekAndLatin/First1KGreek'}


def text(el, tag):
    """Prefer the English child element, else the first one."""
    found = el.findall(TI + tag)
    for f in found:
        if f.get(XL) == 'eng' and (f.text or '').strip():
            return ' '.join(f.text.split())
    for f in found:
        if (f.text or '').strip():
            return ' '.join(f.text.split())
    return ''


def build(clone):
    name = os.path.basename(os.path.normpath(clone))
    repo = REPOS.get(name)
    if not repo:
        sys.exit(f'unknown corpus folder {name!r}; expected one of {list(REPOS)}')
    files = set(subprocess.run(['git', '-C', clone, 'ls-tree', '-r', '--name-only', 'HEAD'],
                               capture_output=True, text=True, check=True).stdout.split())
    base = f'https://raw.githubusercontent.com/{repo}/master/'
    data = os.path.join(clone, 'data')
    works = []
    for tg in sorted(os.listdir(data)):
        tgdir = os.path.join(data, tg)
        tgcts = os.path.join(tgdir, '__cts__.xml')
        if not os.path.isfile(tgcts):
            continue
        try:
            author = text(ET.parse(tgcts).getroot(), 'groupname') or tg
        except ET.ParseError:
            author = tg
        for wk in sorted(os.listdir(tgdir)):
            wcts = os.path.join(tgdir, wk, '__cts__.xml')
            if not os.path.isfile(wcts):
                continue
            try:
                root = ET.parse(wcts).getroot()
            except ET.ParseError:
                continue
            title = text(root, 'title') or wk
            eds = []
            for kind in ('edition', 'translation'):
                for e in root.findall(TI + kind):
                    urn = e.get('urn', '')
                    lang = e.get(XL, '')
                    path = f'data/{tg}/{wk}/{urn.split(":")[-1]}.xml'
                    if path not in files:
                        continue  # catalogued but not present in the repo
                    eds.append({'u': urn.split(':')[-1], 'l': lang, 'k': kind[0],
                                'd': text(e, 'description')[:220], 'p': base + path})
            if eds:
                works.append({'id': f'{tg}.{wk}', 'a': author, 't': title,
                              'lang': root.get(XL, ''), 'src': name, 'e': eds})
    return works


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('clones', nargs='+')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'tools', 'research', 'data', 'classics-catalog.js'))
    a = ap.parse_args()
    works = []
    for c in a.clones:
        w = build(c)
        print(f'{os.path.basename(os.path.normpath(c))}: {len(w)} works', file=sys.stderr)
        works += w
    # First1KGreek overlaps Perseus for some works; keep both, they are different editions.
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/build_classics_catalog.py — open CTS/TEI corpora (CC BY-SA).\n')
        f.write('window.CLASSICS_CATALOG=')
        json.dump(works, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    n_en = sum(any(e['l'] == 'eng' for e in w['e']) for w in works)
    print(f'{len(works)} works, {n_en} with English → {a.out}', file=sys.stderr)


if __name__ == '__main__':
    main()
